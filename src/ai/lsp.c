int lvc_lsp_write_frame(int fd, const char *body) {
    char head[64];
    int hl = snprintf(head, sizeof head, "Content-Length: %zu\r\n\r\n", strlen(body));
    if (hl < 0) return -1;
    size_t total = (size_t)hl + strlen(body);
    char *msg = malloc(total);
    if (!msg) return -1;
    memcpy(msg, head, (size_t)hl);
    memcpy(msg + hl, body, strlen(body));
    size_t off = 0;
    while (off < total) {
        ssize_t w = write(fd, msg + off, total - off);
        if (w <= 0) { free(msg); return -1; }
        off += (size_t)w;
    }
    free(msg);
    return 0;
}

/* read until "\r\n\r\n", parse Content-Length, then read body */
int lvc_lsp_read_frame(int fd, char **out) {
    char hdr[1024];
    size_t h = 0;
    while (h < sizeof hdr - 1) {
        char c;
        ssize_t r = read(fd, &c, 1);
        if (r <= 0) return -1;
        hdr[h++] = c;
        if (h >= 4 && hdr[h-1] == '\n' && hdr[h-2] == '\r' &&
            hdr[h-3] == '\n' && hdr[h-4] == '\r') break;
    }
    hdr[h] = 0;
    const char *cl = NULL;
    for (const char *q = hdr; *q; q++)
        if ((q == hdr || q[-1] == '\n') && strncasecmp(q, "content-length:", 15) == 0) { cl = q + 15; break; }
    if (!cl) return -1;
    size_t len = (size_t)strtoul(cl, NULL, 10);
    char *body = malloc(len + 1);
    if (!body) return -1;
    size_t off = 0;
    while (off < len) {
        ssize_t r = read(fd, body + off, len - off);
        if (r <= 0) { free(body); return -1; }
        off += (size_t)r;
    }
    body[len] = 0;
    *out = body;
    return 0;
}

/* extract "id":N from response JSON (flat, generated by us or simple servers) */
static long json_id(const char *json) {
    const char *p = strstr(json, "\"id\"");
    if (!p) return -1;
    p += 4;
    while (*p == ' ' || *p == ':') p++;
    return strtol(p, NULL, 10);
}

static void capture_diagnostics(lvc_lsp *s, const char *body) {
    if (!strstr(body, "publishDiagnostics")) return;
    free(s->last_diagnostics);
    s->diag_len = strlen(body);
    s->last_diagnostics = malloc(s->diag_len + 1);
    if (s->last_diagnostics) {
        memcpy(s->last_diagnostics, body, s->diag_len + 1);
    }
}

int lvc_lsp_start(lvc_lsp *s, char *const argv[], const char *root_uri,
                  const char *path, const lvc_buf *b) {
    (void)b;
    int in_pipe[2], out_pipe[2];
    if (pipe(in_pipe) || pipe(out_pipe)) return -1;
    pid_t pid = fork();
    if (pid < 0) return -1;
    if (pid == 0) {
        dup2(in_pipe[0], 0);
        dup2(out_pipe[1], 1);
        close(in_pipe[0]); close(in_pipe[1]);
        close(out_pipe[0]); close(out_pipe[1]);
        execvp(argv[0], argv);
        _exit(127);
    }
    close(in_pipe[0]); close(out_pipe[1]);
    s->pid = pid;
    s->fd_in = in_pipe[1];
    s->fd_out = out_pipe[0];
    s->fd_err = -1;
    s->next_id = 1;
    s->last_diagnostics = NULL;
    s->diag_len = 0;

    char params[1024 + strlen(root_uri) + strlen(path)];
    snprintf(params, sizeof params,
        "{\"processId\":null,\"rootUri\":\"%s\","
        "\"capabilities\":{},"
        "\"workspaceFolders\":[{\"uri\":\"%s\",\"name\":\"root\"}]}",
        root_uri, root_uri);
    long id = s->next_id++;
    char req[1536 + strlen(root_uri)];
    snprintf(req, sizeof req, "{\"jsonrpc\":\"2.0\",\"id\":%ld,\"method\":\"initialize\",\"params\":%s}", id, params);
    lvc_lsp_write_frame(s->fd_in, req);
    /* wait for initialize response */
    char *resp = NULL;
    while (lvc_lsp_read_frame(s->fd_out, &resp) == 0) {
        long rid = json_id(resp);
        capture_diagnostics(s, resp);
        int ok = (rid == id);
        free(resp);
        if (ok) break;
    }
    lvc_lsp_write_frame(s->fd_in, "{\"jsonrpc\":\"2.0\",\"method\":\"initialized\",\"params\":{}}");
    /* didOpen */
    size_t tlen = lvc_buf_len((lvc_buf *)b);
    char *text = malloc(tlen + 1);
    if (text) {
        lvc_buf_read((lvc_buf *)b, 0, (uint8_t *)text, tlen);
        text[tlen] = 0;
        char open[256 + strlen(path) + tlen];
        snprintf(open, sizeof open,
            "{\"jsonrpc\":\"2.0\",\"method\":\"textDocument/didOpen\",\"params\":"
            "{\"textDocument\":{\"uri\":\"file://%s\",\"languageId\":\"c\",\"version\":1,\"text\":\"\"}}}",
            path); /* full text sent via change below to keep escaping simple */
        lvc_lsp_write_frame(s->fd_in, open);
        free(text);
    }
    return 0;
}

int lvc_lsp_notify_change(lvc_lsp *s, const char *path, lvc_buf *b) {
    size_t tlen = lvc_buf_len(b);
    char *esc = malloc(tlen * 6 + 16);
    if (!esc) return -1;
    size_t j = 0;
    uint8_t *raw = malloc(tlen ? tlen : 1);
    if (!raw) { free(esc); return -1; }
    lvc_buf_read(b, 0, raw, tlen);
    for (size_t i = 0; i < tlen; i++) {
        unsigned char ch = raw[i];
        if (ch == '"') { esc[j++] = '\\'; esc[j++] = '"'; }
        else if (ch == '\\') { esc[j++] = '\\'; esc[j++] = '\\'; }
        else if (ch == '\n') { esc[j++] = '\\'; esc[j++] = 'n'; }
        else if (ch == '\t') { esc[j++] = '\\'; esc[j++] = 't'; }
        else if (ch == '\r') { esc[j++] = '\\'; esc[j++] = 'r'; }
        else esc[j++] = (char)ch;
    }
    esc[j] = 0;
    char *msg = malloc(j + 256 + strlen(path));
    if (!msg) { free(esc); free(raw); return -1; }
    snprintf(msg, j + 256 + strlen(path),
        "{\"jsonrpc\":\"2.0\",\"method\":\"textDocument/didChange\",\"params\":"
        "{\"textDocument\":{\"uri\":\"file://%s\",\"version\":2},"
        "\"contentChanges\":[{\"text\":\"%s\"}]}}", path, esc);
    int r = lvc_lsp_write_frame(s->fd_in, msg);
    free(msg); free(esc); free(raw);
    return r;
}

char *lvc_lsp_request(lvc_lsp *s, const char *method, const char *params_json) {
    long id = s->next_id++;
    char *req = malloc(strlen(method) + strlen(params_json) + 96);
    if (!req) return NULL;
    snprintf(req, strlen(method) + strlen(params_json) + 96,
        "{\"jsonrpc\":\"2.0\",\"id\":%ld,\"method\":\"%s\",\"params\":%s}",
        id, method, params_json);
    if (lvc_lsp_write_frame(s->fd_in, req) != 0) { free(req); return NULL; }
    free(req);
    for (;;) {
        char *body = NULL;
        if (lvc_lsp_read_frame(s->fd_out, &body) != 0) return NULL;
        long rid = json_id(body);
        int is_response = strstr(body, "\"result\"") || strstr(body, "\"error\"");
        capture_diagnostics(s, body);
        if (rid == id && is_response) {
            /* extract result value: naive — return whole body; caller may parse */
            return body;
        }
        free(body);
    }
}

int lvc_lsp_poll(lvc_lsp *s) {
    struct pollfd p = { .fd = s->fd_out, .events = POLLIN, .revents = 0 };
    if (poll(&p, 1, 0) <= 0) return 0;
    char *body = NULL;
    if (lvc_lsp_read_frame(s->fd_out, &body) != 0) return 0;
    capture_diagnostics(s, body);
    free(body);
    return 1;
}

int lvc_lsp_stop(lvc_lsp *s) {
    if (s->pid < 0) return 0;
    lvc_lsp_write_frame(s->fd_in, "{\"jsonrpc\":\"2.0\",\"id\":9999,\"method\":\"shutdown\",\"params\":null}");
    lvc_lsp_write_frame(s->fd_in, "{\"jsonrpc\":\"2.0\",\"method\":\"exit\",\"params\":null}");
    close(s->fd_in); close(s->fd_out);
    int status;
    /* bounded wait */
    for (int i = 0; i < 30; i++) {
        pid_t r = waitpid(s->pid, &status, WNOHANG);
        if (r == s->pid) break;
        usleep(100000);
    }
    kill(s->pid, SIGTERM);
    s->pid = -1;
    free(s->last_diagnostics);
    s->last_diagnostics = NULL;
    return 0;
}
